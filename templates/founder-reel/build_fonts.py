"""Download the template's OFL fonts (Cormorant Garamond + Jost, latin) and embed
them as base64 in fonts.ts next to FounderReel.tsx.

Why embedded: the headless render browser here cannot reach Google Fonts through
the proxy, and fetching fonts from the Remotion dev server can stall behind video
frame requests in parallel tabs. Decoding an in-bundle buffer needs no network.

usage: python templates/founder-reel/build_fonts.py <project_dir>
"""
import base64
import re
import subprocess
import sys
from pathlib import Path

CSS = ("https://fonts.googleapis.com/css2?family=Cormorant+Garamond:ital,wght@0,300;0,500;0,600;"
       "1,300;1,500;1,600&family=Jost:wght@400;500&display=block")
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/131.0 Safari/537.36"


def main(project: str) -> None:
    out = Path(project) / "fonts.ts"
    css = subprocess.run(["curl", "-s", "-A", UA, CSS], capture_output=True, text=True, check=True).stdout
    rows = []
    for subset, body in re.findall(r"/\*\s*([\w-]+)\s*\*/\s*@font-face\s*{([^}]*)}", css):
        if subset != "latin":
            continue
        fam = re.search(r"font-family:\s*'([^']+)'", body).group(1)
        style = re.search(r"font-style:\s*(\w+)", body).group(1)
        weight = re.search(r"font-weight:\s*(\d+)", body).group(1)
        url = re.search(r"url\((https://[^)]+\.woff2)\)", body).group(1)
        data = subprocess.run(["curl", "-s", url], capture_output=True, check=True).stdout
        rows.append(f'  {{ family: "{fam}", style: "{style}", weight: "{weight}", b64: "{base64.b64encode(data).decode()}" }},')
    out.write_text("// Generated by build_fonts.py — OFL fonts embedded for offline rendering.\n"
                   "export const FONT_DATA: { family: string; style: string; weight: string; b64: string }[] = [\n"
                   + "\n".join(rows) + "\n];\n")
    print(f"wrote {out} ({len(rows)} faces)")


if __name__ == "__main__":
    main(sys.argv[1])
